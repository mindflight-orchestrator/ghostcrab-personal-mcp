#!/usr/bin/env node
/**
 * Render Mermaid classDiagram from LinkML YAML slices.
 * Usage:
 *   node scripts/render-linkml-ontology-graph.mjs
 *   node scripts/render-linkml-ontology-graph.mjs --check
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const SLICES = [
  {
    slug: "memory-model",
    yaml: "docs/explanation/ontology/linkml/ghostcrab-docs/memory-model.yaml",
    ontologyId: "ghostcrab-docs::memory-model",
    docSource: "../../03-memoire-mcp-facettes-graphe-projections.md"
  },
  {
    slug: "query-layers",
    yaml: "docs/explanation/ontology/linkml/ghostcrab-docs/query-layers.yaml",
    ontologyId: "ghostcrab-docs::query-layers",
    docSource: "../../../methodology/ghostcrab-query-layers.md"
  },
  {
    slug: "methodology-loop",
    yaml: "docs/explanation/ontology/linkml/ghostcrab-docs/methodology-loop.yaml",
    ontologyId: "ghostcrab-docs::methodology-loop",
    docSource: "../../../methodology/universal_methodology.md"
  },
  {
    slug: "import-paths",
    yaml: "docs/explanation/ontology/linkml/ghostcrab-docs/import-paths.yaml",
    ontologyId: "ghostcrab-docs::import-paths",
    docSource:
      "../../methode-starterkit/06-voies-import-ontologie-et-tabulaire.md"
  }
];

const checkMode = process.argv.includes("--check");
const diagramsDir = join(root, "docs/explanation/ontology/diagrams");
mkdirSync(diagramsDir, { recursive: true });

function sha256Short(text) {
  return createHash("sha256").update(text).digest("hex").slice(0, 12);
}

function parseLinkmlClasses(schema) {
  const classes = schema.classes ?? {};
  const entries = [];
  for (const [name, def] of Object.entries(classes)) {
    if (!def || typeof def !== "object") continue;
    entries.push({
      name,
      isAbstract: Boolean(def.abstract),
      parent: typeof def.is_a === "string" ? def.is_a : null,
      description: typeof def.description === "string" ? def.description : ""
    });
  }
  return entries;
}

function parseLinkmlEnums(schema) {
  const enums = schema.enums ?? {};
  const entries = [];
  for (const [name, def] of Object.entries(enums)) {
    const values = Object.keys(def?.permissible_values ?? {});
    entries.push({ name, values });
  }
  return entries;
}

function mermaidClassDiagram(classes) {
  const lines = ["```mermaid", "classDiagram"];
  const concrete = classes.filter((c) => !c.isAbstract);
  const abstract = classes.filter((c) => c.isAbstract);

  for (const c of abstract) {
    lines.push(`    class ${c.name} {`);
    lines.push("      <<abstract>>");
    lines.push("    }");
  }
  for (const c of concrete) {
    const note = c.description
      ? c.description.replace(/[\n\r"]/g, " ").slice(0, 80)
      : "";
    if (note) {
      lines.push(`    class ${c.name} {`);
      lines.push(`      ${note}`);
      lines.push("    }");
    } else {
      lines.push(`    class ${c.name}`);
    }
  }
  for (const c of classes) {
    if (c.parent) {
      lines.push(`    ${c.parent} <|-- ${c.name}`);
    }
  }
  lines.push("```");
  return lines.join("\n");
}

function mermaidEnumFlowchart(enums) {
  if (enums.length === 0) return "";
  const lines = ["", "### Enumerations", "", "```mermaid", "flowchart TB"];
  for (const e of enums) {
    lines.push(`    subgraph ${e.name} [${e.name}]`);
    for (const v of e.values) {
      lines.push(`      ${e.name}_${v}[${v}]`);
    }
    lines.push("    end");
  }
  lines.push("```");
  return lines.join("\n");
}

function renderSlice(slice) {
  const yamlPath = join(root, slice.yaml);
  const raw = readFileSync(yamlPath, "utf8");
  const schema = parseYaml(raw);
  const classes = parseLinkmlClasses(schema);
  const enums = parseLinkmlEnums(schema);
  const hash = sha256Short(raw);

  const md = [
    `# ${slice.slug} — LinkML class graph`,
    "",
    "| Field | Value |",
    "|-------|-------|",
    `| ontology-id | \`${slice.ontologyId}\` |`,
    `| source yaml | [\`${basename(slice.yaml)}\`](../linkml/ghostcrab-docs/${basename(slice.yaml)}) |`,
    `| yaml sha256 (12) | \`${hash}\` |`,
    `| doc source | [\`${slice.docSource}\`](${slice.docSource}) |`,
    "",
    "> Generated by `node scripts/render-linkml-ontology-graph.mjs`. Do not edit by hand.",
    "",
    "## Class hierarchy",
    "",
    mermaidClassDiagram(classes),
    mermaidEnumFlowchart(enums),
    ""
  ].join("\n");

  return {
    md,
    hash,
    outPath: join(
      root,
      "docs/explanation/ontology/diagrams",
      `${slice.slug}.md`
    )
  };
}

let failed = false;
for (const slice of SLICES) {
  const { md, outPath } = renderSlice(slice);
  if (checkMode) {
    if (!existsSync(outPath)) {
      console.error(`[check] missing ${outPath}`);
      failed = true;
      continue;
    }
    const committed = readFileSync(outPath, "utf8");
    if (committed !== md) {
      console.error(`[check] drift: ${outPath} (re-run render script)`);
      failed = true;
    } else {
      console.log(`[check] ok ${basename(outPath)}`);
    }
  } else {
    writeFileSync(outPath, md);
    console.log(`wrote ${outPath}`);
  }
}

if (failed) process.exit(1);
